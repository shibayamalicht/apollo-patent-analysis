# ステータスは出願年に応じた現実的な分布にする（審査には年単位の時間がかかるため、
# 古い出願ほど審査完了（登録/拒絶/取下）が多く、新しい出願は公開・審査中が大半になる）
def _pick_status(rng, year):
    if year <= 2018:      # 審査がほぼ完了している層
        pool = ["登録"] * 55 + ["拒絶"] * 22 + ["取下"] * 15 + ["登録"] * 8
    elif year <= 2021:    # 審査進行中の層
        pool = ["登録"] * 40 + ["審査中"] * 18 + ["拒絶"] * 17 + ["公開"] * 18 + ["取下"] * 7
    else:                 # 出願から日が浅い層
        pool = ["公開"] * 55 + ["審査中"] * 35 + ["登録"] * 8 + ["拒絶"] * 2
    return pool[int(rng.integers(len(pool)))]


def _person(rng):
    return SURNAMES[int(rng.integers(len(SURNAMES)))] + " " + GIVEN[int(rng.integers(len(GIVEN)))]


def _pick(rng, pool):
    return pool[int(rng.integers(len(pool)))]


def main():
    rng = np.random.default_rng(SEED)
    names, weights = zip(*APPLICANTS)
    w = np.array(weights, dtype=float)
    w /= w.sum()

    rows = []
    serial = 0

    def add_row(theme, ipc_pool, vocab, year_mu, cross_vocab=None):
        nonlocal serial
        serial += 1
        year = int(np.clip(rng.normal(year_mu, 2.2), 2015, 2025))
        month = int(rng.integers(1, 13))
        day = int(rng.integers(1, 29))
        applicant = names[int(rng.choice(len(names), p=w))]
        n_inv = int(rng.integers(1, 4))
        # set だと文字列ハッシュの乱数化で並び順が実行ごとに変わりCSVが再現しないため、
        # dict.fromkeys で重複除去しつつ挿入順（rng の生成順）を保持する
        inventors = ";".join(dict.fromkeys(_person(rng) for _ in range(n_inv)))

        mat = _pick(rng, vocab["material"])
        prob = _pick(rng, vocab["problem"])
        sol = _pick(rng, vocab["solution"])
        eff = _pick(rng, vocab["effect"])
        # ノイズ用: 別テーマの語彙を混ぜて境界を曖昧にする
        if cross_vocab is not None:
            eff = _pick(rng, cross_vocab["effect"])

        title = f"{mat}及びその製造方法" if serial % 3 else f"{mat}を用いた全固体電池"
        abstract = (
            f"本発明は、{mat}に関する。従来技術では{prob}という課題があった。"
            f"本発明では、{sol}ことにより、{eff}。"
            f"これにより全固体リチウムイオン二次電池の実用化に寄与する。"
        )
        claim = f"{mat}を備え、{sol}ことを特徴とする全固体電池。"
        ipcs = ";".join(sorted(set([_pick(rng, ipc_pool), _pick(rng, ipc_pool)])))

        rows.append({
            "出願番号": f"特願20{year-2000:02d}-{100000+serial:06d}",
            "出願日": f"{year}/{month:02d}/{day:02d}",
            "発明の名称": title,
            "要約": abstract,
            "請求の範囲": claim,
            "出願人": applicant,
            "発明者": inventors,
            "IPC": ipcs,
            "ステータス": _pick_status(rng, year),
        })

    for theme, n, year_mu, ipc_pool, vocab in THEMES:
        for _ in range(n):
            add_row(theme, ipc_pool, vocab, year_mu)

    # ノイズ: 2テーマの語彙を混成（境界領域・萌芽っぽい特許）
    for i in range(N_NOISE):
        a = THEMES[int(rng.integers(len(THEMES)))]
        b = THEMES[int(rng.integers(len(THEMES)))]
        add_row(a[0], a[3], a[4], 2023, cross_vocab=b[4])

    # 共同出願の付与（出願人ネットワーク=企業アライアンス分析用）。
    # 単独出願の行の出願人へ相手方を「;」区切りで追記するだけなので、
    # 他カラムの生成結果・行数・出現順は変えない。
    for lead, partners, k in ALLIANCES:
        idx = np.array([i for i, r in enumerate(rows) if r["出願人"] == lead])
        rng.shuffle(idx)
        for i in idx[:k]:
            rows[i]["出願人"] = ";".join([lead] + partners)

    df = pd.DataFrame(rows).sample(frac=1.0, random_state=SEED).reset_index(drop=True)
    df.to_csv("sample_patents.csv", index=False, encoding="utf-8-sig")
    print(f"生成完了: sample_patents.csv ({len(df)}件)")
    print(df.head(3).to_string())


if __name__ == "__main__":
    main()
